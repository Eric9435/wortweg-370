const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const initial=JSON.parse(fs.readFileSync('content/v1/pack.json','utf8'));
const script=fs.readFileSync('live-content.js','utf8');
const html='<!doctype html><html><head></head><body><main><section class="section active" id="dashboard"><div class="ww-menu-options"></div></section><section id="settings" class="section"><div class="settings-grid"></div></section></main></body></html>';
function setup(cache,networkPack){
 const dom=new JSDOM(html,{url:'https://localhost/index.html',runScripts:'outside-only'});
 const w=dom.window;
 w.scrollTo=()=>{};
 if(cache)w.localStorage.setItem('wortweg370-live-pack-v1',JSON.stringify(cache));
 let online=networkPack;
 let requests=[];
 w.fetch=async(url)=>{
  requests.push(String(url));
  if(!online)throw Error('offline');
  const obj=String(url).startsWith('./')?initial:online;
  return {ok:true,headers:{get:()=>null},text:async()=>JSON.stringify(obj)};
 };
 w.WortWeg={navigate(id){w.document.querySelectorAll('.section').forEach(s=>s.classList.toggle('active',s.id===id))}};
 w.eval(script);
 return {dom,w,setOnline:p=>online=p,requests};
}
async function wait(){await new Promise(r=>setTimeout(r,25))}
(async()=>{
 assert.equal(initial.schema,1);
 assert.equal(initial.lessons.length,4);
 assert.equal(initial.lessons.reduce((sum,l)=>sum+l.words.length,0),48);
 const {dom,w,setOnline,requests}=setup(null,initial);
 await wait();
 const api=w.WortWegLive;
 assert.ok(api,'Updater is initialized in the bundled UI');
 assert.equal(api.getPack().version,1);
 assert.equal(w.document.querySelectorAll('.ww-live-lesson').length,4);
 assert.ok(requests.some(url=>url.startsWith('./')),'Bundled starter pack is readable');
 assert.ok(requests.some(url=>url.startsWith('https:')),'Public website content is checked');
 const menu=w.document.querySelector('.ww-live-menu-option');menu.click();
 assert.equal(w.document.querySelector('.section.active').id,'ww-live','New lessons open as a separate page');
 const lesson=w.document.querySelector('.ww-live-lesson');lesson.click();
 assert.equal(w.document.getElementById('ww-live-list').hidden,true);
 assert.equal(w.document.getElementById('ww-live-quiz').hidden,false);
 const current=w.document.querySelector('.ww-live-word').textContent;
 const correct=initial.lessons[0].words.find(word=>word.de===current);
 assert.ok(correct);
 const choices=[...w.document.querySelectorAll('.ww-live-answer')];
 const right=choices.find(b=>b.textContent===correct.en);
 assert.ok(right);
 right.click();right.click();
 const key='wortweg370-live-progress-v1:guest';
 assert.equal(JSON.parse(w.localStorage.getItem(key))[correct.id].answered,1,'No double counting on repeated taps');
 const newer=JSON.parse(JSON.stringify(initial));newer.version=2;newer.updatedAt='2026-10-09';
 newer.lessons[0].words.push({id:'greetings-999',de:'Willkommen',en:'Welcome',my:'ကြိုဆိုပါတယ်'});
 setOnline(newer);
 await api.refresh();
 assert.equal(api.getPack().version,2,'Later website vocab updates apply without an APK');
 assert.ok(JSON.parse(w.localStorage.getItem('wortweg370-live-pack-v1')).lessons[0].words.some(x=>x.de==='Willkommen'));
 assert.equal(JSON.parse(w.localStorage.getItem(key))[correct.id].answered,1,'New versions never erase existing answers');
 setOnline(initial);await api.refresh();
 assert.equal(api.getPack().version,2,'Never downgrade cached content');
 const malicious=JSON.parse(JSON.stringify(newer));malicious.version=3;
 malicious.lessons[0].title='<img src=x onerror=alert(1)>';
 setOnline(malicious);await api.refresh();
 w.document.getElementById('ww-live-back').click();menu.click();
 assert.equal(w.document.querySelector('.ww-live-lesson').querySelector('img'),null,'Data never becomes executable HTML');
 assert.match(w.document.querySelector('.ww-live-lesson').textContent,/img src/);
 const invalid=JSON.parse(JSON.stringify(newer));invalid.version=4;invalid.lessons[0].words[0].en='';
 setOnline(invalid);await api.refresh();
 assert.equal(api.getPack().version,3,'Malformed remote content is rejected safely');
 w.dispatchEvent(new w.CustomEvent('wortweg:account',{detail:{uid:'account-A'}}));
 assert.equal(w.document.querySelector('.ww-live-quiz').hidden,true,'Switching accounts ends an active quiz');
 assert.equal(JSON.parse(w.localStorage.getItem(key))[correct.id].answered,1,'Guest record stays isolated');
 menu.click();w.document.querySelector('.ww-live-lesson').click();
 w.document.querySelector('.ww-live-answer').click();
 assert.ok(w.localStorage.getItem('wortweg370-live-progress-v1:account-A'),'Signed-in progress has its own storage key');
 w.dispatchEvent(new w.CustomEvent('wortweg:account',{detail:{uid:null}}));
 assert.equal(JSON.parse(w.localStorage.getItem(key))[correct.id].answered,1,'Signed-in actions do not alter prior guest record');
 const cache=JSON.parse(w.localStorage.getItem('wortweg370-live-pack-v1'));dom.window.close();
 const second=setup(cache,null);await wait();
 assert.equal(second.w.WortWegLive.getPack().version,3,'Offline restart uses the newest cached pack');
 assert.equal(second.w.document.querySelectorAll('.ww-live-lesson').length,4);
 second.dom.window.close();
 console.log('PASS: bundled offline content, website update, quiz persistence, version monotonicity, invalid-data rejection, no HTML injection, and account separation.');
})().catch(e=>{console.error(e);process.exitCode=1});
