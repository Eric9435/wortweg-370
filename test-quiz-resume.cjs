/* Quiz checkpoint regression: stop, reload, continue, confirm replacement and account isolation. */
const fs=require('node:fs'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
function launch(data={}){
 const errors=[];
 const d=new JSDOM(html,{url:'https://eric9435.github.io/wortweg-370/',runScripts:'dangerously',beforeParse(w){
  w.scrollTo=()=>{};w.structuredClone=structuredClone;
  for(const [k,v] of Object.entries(data))w.localStorage.setItem(k,v);
  w.addEventListener('error',e=>errors.push(String(e.message)));
 }});
 assert.deepEqual(errors,[]);
 return d;
}
const state=d=>Object.fromEntries(Array.from({length:d.window.localStorage.length},(_,i)=>{
 const k=d.window.localStorage.key(i);return [k,d.window.localStorage.getItem(k)];
}));
const click=(d,id)=>{const e=d.window.document.getElementById(id);assert(e,'Missing '+id);e.click();};
const getSession=(d,user='guest')=>JSON.parse(d.window.localStorage.getItem('wortweg370-quiz-session-v1:'+user)||'null');
const a=launch();
a.window.document.getElementById('quizLength').value='all';
a.window.document.getElementById('mode').value='topic1';
click(a,'startQuiz');
let stored=getSession(a);
const data=JSON.parse(a.window.document.getElementById('data').textContent);
assert.equal(stored.keys.length,data.curated.length,'All topic words saved in original question order');
assert.equal(stored.i,0);
assert.equal(stored.locked,false);
assert.equal(a.window.document.getElementById('quizResume').hidden,false);
const originalId=stored.id;
const firstWord=a.window.document.querySelector('#quiz .question').textContent;
const firstChoices=[...a.window.document.querySelectorAll('#answerButtons button')].map(x=>x.textContent);
a.window.document.querySelector('#answerButtons button').click();
click(a,'submitAnswer');
assert.equal(getSession(a).locked,true,'Checked answer checkpoint is stored');
assert.equal(getSession(a).i,0);
const answered=a.window.WortWeg.getProgress().answered;
assert.equal(answered,1);
click(a,'submitAnswer');
assert.equal(getSession(a).i,1,'Moving to next question persists index');
const secondWord=a.window.document.querySelector('#quiz .question').textContent;
a.window.document.querySelectorAll('#answerButtons button')[2].click();
const chosen=getSession(a);
assert.equal(chosen.chosen,2);
assert.equal(chosen.locked,false);
a.window.WortWeg.navigate('study');
assert.equal(a.window.document.getElementById('quizResume').hidden,false,'Resume card visible on return to setup');
let copy=state(a);a.window.close();
const b=launch(copy);
assert.equal(b.window.document.getElementById('quizResume').hidden,false,'Resume card returns after app restart');
assert.match(b.window.document.getElementById('resumeSummary').textContent,/Question 2 of/);
const prior=b.window.localStorage.getItem('wortweg370-quiz-session-v1:guest');
click(b,'startQuiz');
assert.equal(b.window.document.getElementById('ww-quiz-replace-dialog').hidden,false,'New quiz needs explicit replacement decision');
assert.equal(b.window.localStorage.getItem('wortweg370-quiz-session-v1:guest'),prior,'Showing confirmation does not wipe the old session');
click(b,'ww-quiz-replace-cancel');
assert.equal(b.window.document.getElementById('ww-quiz-replace-dialog').hidden,true);
assert.equal(getSession(b).id,originalId);
click(b,'continueQuiz');
assert.equal(b.window.document.querySelector('.section.active').id,'quiz');
assert.equal(b.window.document.querySelector('#quiz .question').textContent,secondWord,'Resume restores the exact word');
assert.equal(b.window.document.getElementById('quizCounter').textContent,'2 / '+data.curated.length);
assert.equal(b.window.document.querySelectorAll('#answerButtons button')[2].getAttribute('aria-pressed'),'true','Selected unchecked answer is restored');
assert.equal(b.window.WortWeg.getProgress().answered,answered,'Resume never recounts completed answers');
click(b,'submitAnswer');
assert.equal(getSession(b).locked,true,'Checked answer checkpoint saved');
const recorded=b.window.WortWeg.getProgress().answered;
copy=state(b);b.window.close();
const c=launch(copy);
click(c,'continueQuiz');
assert.equal(c.window.document.querySelector('#quiz .question').textContent,secondWord);
assert.equal(c.window.document.getElementById('submitAnswer').textContent,'Next question →','Already checked answer stays checked on restore');
assert.equal(c.window.WortWeg.getProgress().answered,recorded,'Checked answer is not scored twice');
click(c,'submitAnswer');
assert.equal(getSession(c).i,2);
c.window.WortWeg.navigate('study');
click(c,'startQuiz');
assert.equal(c.window.document.getElementById('ww-quiz-replace-dialog').hidden,false);
click(c,'ww-quiz-replace-continue');
assert.equal(getSession(c).id,originalId,'Continue from modal preserves quiz identity');
c.window.WortWeg.navigate('study');
click(c,'newQuizFromResume');
assert.equal(c.window.document.getElementById('ww-quiz-replace-dialog').hidden,false);
click(c,'ww-quiz-replace-new');
assert.notEqual(getSession(c).id,originalId,'Explicit New creates a new session');
assert.equal(getSession(c).i,0,'New quiz starts at the beginning only after confirmation');
assert.equal(c.window.WortWeg.getProgress().answered,recorded,'New quiz does not erase accumulated learning history');
// Google-account sessions are never exposed across account switches.
c.window.WortWeg.switchProfile('user-a');
assert.equal(c.window.document.getElementById('quizResume').hidden,true,'New account cannot see guest session');
click(c,'startQuiz');
assert.ok(getSession(c,'user-a')?.keys.length);
c.window.WortWeg.switchProfile('user-b');
assert.equal(c.window.document.getElementById('quizResume').hidden,true,'Different signed-in account starts clean');
c.window.WortWeg.switchProfile('user-a');
assert.equal(c.window.document.getElementById('quizResume').hidden,false,'Return to original account restores its checkpoint');
c.window.close();
// Performance regression: an A2 All quiz should never rewrite a huge 932-word
// manifest on every tap. Only a tiny cursor tracks position/answer state.
const long=launch();
long.window.document.getElementById('mode').value='bank';
long.window.document.getElementById('level').value='A2';
long.window.document.getElementById('quizLength').value='all';
click(long,'startQuiz');
const longManifest=long.window.localStorage.getItem('wortweg370-quiz-session-v1:guest');
const longData=JSON.parse(longManifest);
assert.ok(longData.keys.length>100,'Long-quiz optimization is exercised');
long.window.document.querySelector('#answerButtons button').click();
const firstCursor=JSON.parse(long.window.localStorage.getItem('wortweg370-quiz-cursor-v1:guest'));
assert.equal(firstCursor.chosen,0,'Option choice is saved in the lightweight cursor');
assert.equal(long.window.localStorage.getItem('wortweg370-quiz-session-v1:guest'),longManifest,'Selecting a choice does not rewrite the full word order');
click(long,'submitAnswer');
const totalSaved=long.window.WortWeg.getProgress().answered;
click(long,'submitAnswer');
const movedCursor=JSON.parse(long.window.localStorage.getItem('wortweg370-quiz-cursor-v1:guest'));
assert.equal(movedCursor.i,1,'Cursor saves the next question immediately');
assert.equal(long.window.localStorage.getItem('wortweg370-quiz-session-v1:guest'),longManifest,'Checking and advancing do not rewrite the word manifest');
assert.ok(JSON.stringify(movedCursor).length<JSON.stringify(longData).length/2,'Cursor is much smaller than saved word bank manifest');
const longState=state(long);long.window.close();
const resumedLong=launch(longState);
click(resumedLong,'continueQuiz');
assert.equal(resumedLong.window.document.getElementById('quizCounter').textContent,'2 / '+longData.keys.length,'Full A2 quiz resumes from exact position after reload');
assert.equal(resumedLong.window.WortWeg.getProgress().answered,totalSaved,'Resume does not count answers twice');
resumedLong.window.close();
assert(fs.readFileSync('extra-progress-sync.js','utf8').includes("['quizCursor'"),'Cloud sync includes long-quiz cursor');
console.log('PASS: offline quiz resume, Continue/New, long All-question cursor performance and account isolation');
