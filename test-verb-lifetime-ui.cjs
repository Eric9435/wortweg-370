/* End-to-end Lifetime Verbs browser smoke test with real WortWeg sources. */
'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const read=p=>fs.readFileSync(p,'utf8');
const html=read('verb-forms.html'),js=read('verb-lifetime.js'),sw=read('sw.js');
const data=JSON.parse(read('assets/german-verbs-lifetime.json'));
const gloss=JSON.parse(read('assets/german-verbs-myanmar.json'));
const index=read('index.html');
const match=index.match(/<script type="application\/json" id="data">([\s\S]*?)<\/script>/);
assert(match,'Word Bank embedded JSON missing');
const bank=JSON.parse(match[1]);
const typed=[...bank.bank,...bank.curated].filter(w=>['verb','modal verb','verb phrase'].includes(w.type))
  .map(w=>({de:w.de,en:w.en,mm:w.mm||w.my,level:w.level,type:w.type}));
const dom=new JSDOM(html,{url:'https://localhost/verb-forms.html',runScripts:'outside-only'});
const w=dom.window,d=w.document;
w.sessionStorage.setItem('wortweg:verb-forms:source:v3',JSON.stringify(typed));
w.fetch=async url=>{
 if(url.endsWith('german-verbs-lifetime.json'))return {ok:true,json:async()=>data};
 if(url.endsWith('german-verbs-myanmar.json'))return {ok:true,json:async()=>gloss};
 const part=url.match(/assets\/verb-sentences\/part-(\d{2})\.json$/);
 if(part)return {ok:true,json:async()=>JSON.parse(read('assets/verb-sentences/part-'+part[1]+'.json'))};
 throw Error('Unexpected request '+url);
};
w.eval(js);
const ready=async()=>{for(let i=0;i<60;i++){if(w.WortWegLifetimeVerbs?.total===8000&&w.WortWegLifetimeVerbs?.wortweg===360&&d.getElementById('gloss-status').textContent.includes('8,000'))return;await new Promise(resolve=>setTimeout(resolve,50));}throw Error('Lifetime dictionary did not finish loading');};
const input=(id,value)=>{const n=d.getElementById(id);n.value=value;n.dispatchEvent(new w.Event(n.tagName==='INPUT'?'input':'change',{bubbles:true}));};
const total=()=>Number(d.getElementById('result').textContent.match(/[\d,]+/)[0].replaceAll(',',''));
const shown=()=>[...d.querySelectorAll('#rows tr')].map(r=>[...r.querySelectorAll('td')].map(c=>c.textContent));
(async()=>{
 await ready();
 assert.equal(w.WortWegLifetimeVerbs.total,8000,'All dictionary lemmas and source-specific manual additions');
 assert.equal(w.WortWegLifetimeVerbs.wortweg,360,'Raw WortWeg headwords must not merge reflexive or prepositional versions');
 assert.equal(total(),8000);
 assert.equal(gloss.rows.length,8000,'Expanded Myanmar data includes every verb');
 assert.match(d.getElementById('gloss-status').textContent,/8,000 entries loaded/);
 input('collection','additional');input('query','aalen');
 assert.equal(total(),1,'Rare lemma remains searchable');
 assert(shown()[0][4].includes('နေရောင်ခံ'),'Auto Myanmar gloss must be visible');
 assert(shown()[0][4].includes('Auto translation · unverified'),'Auto gloss must not masquerade as curated WortWeg content');
 d.getElementById('reset').click();
 assert.equal(d.querySelectorAll('#rows tr').length,24,'Comfortable mobile page size');
 assert.equal(d.getElementById('saved-count').textContent,'0');
 assert(d.querySelector('td:nth-child(9) .actionbar'),'Study controls must be present');
 const firstVerb=d.querySelector('#rows tr td').textContent;
 d.querySelector('#rows tr .actionbar button').click();
 assert.equal(d.getElementById('saved-count').textContent,'1','Saved words should persist');
 assert(JSON.parse(w.localStorage.getItem('wortweg:verb-studio:saved:v1')).includes(firstVerb));
 input('collection','saved');assert.equal(total(),1,'Saved list filters correctly');
 d.getElementById('practice').click();
 assert.equal(d.getElementById('practice').getAttribute('aria-pressed'),'true');
 assert.equal(shown()[0][1],'••••','Practice hides V2');
 assert.equal(shown()[0][2],'••••','Practice hides V3');
 d.querySelector('.actionbar .reveal').click();
 assert.notEqual(shown()[0][1],'••••','Reveal restores V2');
 assert.notEqual(shown()[0][2],'••••','Reveal restores V3');
 d.getElementById('practice').click();
 d.querySelector('#rows tr .actionbar button').click();
 assert.equal(total(),0,'Unsave updates Saved view');
 d.getElementById('reset').click();
 input('page-size','50');assert.equal(d.querySelectorAll('#rows tr').length,50,'Page size selection works');
 d.getElementById('reset').click();
 assert.equal(d.getElementById('sort').value,'course','WortWeg-first sorting should be the default');
 input('sort','az');
 assert.equal(shown()[0][0],'aalen','Alphabetical list must start with the first dictionary lemma');
 input('sort','course');
 input('collection','wortweg');assert.equal(total(),360);
 input('query','treffen');assert(total()>=2,'treffen and sich treffen must remain searchable');
 const tref=shown().map(row=>row[0]);
 assert(tref.includes('sich treffen')&&tref.includes('treffen'),'Reflexive and base verbs must remain distinct');
 input('query','abstrahieren');assert.equal(total(),2,'abstrahieren and abstrahieren von remain distinct');
 input('query','ad absurdum führen');assert.equal(total(),1,'A tagged verb phrase must be shown');
 input('query','angemessen');assert.equal(total(),0,'Adjective must not count as a verb');
 input('query','');input('collection','all');
 input('query','gehen');assert.equal(total(),1);
 const examplesButton=[...d.querySelectorAll('#rows tr button')].find(x=>x.textContent==='3 Sentences');
 assert(examplesButton,'Every verb must have a three-sentence action');
 examplesButton.click();
 for(let i=0;i<40&&!d.getElementById('example-content').textContent.includes('Ich möchte nach Hause gehen.');i++)await new Promise(resolve=>setTimeout(resolve,20));
 assert(d.getElementById('example-content').textContent.includes('Ich möchte nach Hause gehen.'),'V1 German appears');
 assert(d.getElementById('example-content').textContent.includes('Gestern ging ich nach Hause.'),'V2 German appears');
 assert(d.getElementById('example-content').textContent.includes('Ich bin gestern nach Hause gegangen.'),'V3 German appears');
 assert(d.getElementById('example-content').textContent.includes('I want to go home.'),'English example appears');
 assert(d.getElementById('example-content').textContent.includes('အိမ်ပြန်ချင်တယ်'),'Myanmar example appears');
 assert.match(d.getElementById('example-status').textContent,/not independently verified/);
 assert.equal(d.getElementById('example-content').querySelectorAll('section').length,3,'Exactly 3 form cards');
 d.getElementById('example-close').click();
 input('query','abwiegen');assert.equal(total(),1);assert.deepEqual(shown()[0].slice(0,3),['abwiegen','wog ab','abgewogen']);
 input('query','abstrahieren');assert.equal(total(),1);assert.deepEqual(shown()[0].slice(0,3),['abstrahieren','abstrahierte','abstrahiert']);
 input('query','');input('level','A1');assert(total()>40&&total()<100,'CEFR A1 should show tagged WortWeg entries, not falsely inferred levels');
 input('level','All');input('status','incomplete');assert.equal(total(),17,'Dataset contains 17 genuinely incomplete V2/V3 records');
 assert(shown().every(row=>row[row.length-2]==='Needs verification'),'Incomplete entries must be flagged clearly');
 input('status','all');input('collection','additional');assert.equal(total(),7642,'Expanded-only count should exclude 357 WortWeg lemma cores');
 assert(d.getElementById('level').disabled,'Expanded-only lexicon has no independent CEFR rating');
 d.getElementById('reset').click();
 assert.equal(total(),8000,'Reset must recover entire dictionary');
 assert(!d.getElementById('level').disabled,'Reset must restore CEFR filter');
 assert.equal(Number(d.getElementById('pattern').textContent.replaceAll(',','')),7642);
 assert(html.includes('@media(max-width:1280px)')&&html.includes('grid-template-columns'),'Tablet/mobile card layout is required');
 assert(html.includes('UPDATED 2026-11-03'),'Version marker must be visible to diagnose stale cache');
 assert(js.includes("cache:'no-cache'"),'Refresh must request updated data');
 assert(html.includes('CC BY-SA 4.0'),'Data attribution is required');
 assert(html.includes('id="sort"')&&html.includes('Update app &amp; data'),'Sort and update affordances must exist');
 assert(js.includes('translate.google.com/?sl=de&tl='),'External translations must be explicitly opt-in');
 assert(js.includes('External · unverified'),'Automatic translations must not be presented as verified');
 assert(Number(sw.match(/wortweg370-v(\d+)/)?.[1])>=113,'PWA cache version must advance');
 assert(sw.includes("'./verb-studio.css'"),'Pro stylesheet must be cached offline');
 assert(sw.includes("'./assets/german-verbs-myanmar.json'"),'Expanded Myanmar glossary must work offline');
 assert(sw.includes("'./assets/verb-sentences/part-01.json'"),'Three-sentence packs must be offline');
 assert(read('mobile/scripts/prepare.mjs').includes("'assets/verb-sentences'"),'Native package needs all example packs');
 assert(html.includes('verb-studio.css?v=1')&&html.includes('id="practice"'),'Pro controls and CSS must load');
 assert(read('mobile/scripts/prepare.mjs').includes("'verb-studio.css'"),'Native package includes style sheet');
 console.log('PASS: lifetime verb page loads 8000 total / 360 WortWeg source entries, search, filtering and mobile layout');
 dom.window.close();
})().catch(err=>{console.error(err);process.exitCode=1});